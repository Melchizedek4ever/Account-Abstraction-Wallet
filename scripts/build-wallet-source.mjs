// Writes the wallet source the app deploys for each user. Relative references
// to the shared contracts become absolute references to the testnet deployment.
import { readFileSync, writeFileSync } from "node:fs";

const { deployer, sbtc } = JSON.parse(readFileSync("deployments/testnet.json", "utf8"));
const shared = ["extension-trait", "rule-set-trait", "sip-009-trait", "sip-010-trait", "standard-rules", "emergency-rules"];
let code = readFileSync("contracts/smart-wallet.clar", "utf8");
for (const name of shared)
  code = code.replace(new RegExp(`(?<=[\\s(])\\.${name}(?![\\w-])`, "g"), `'${deployer}.${name}`);
if (/[\s(]\.[a-z]/.test(code.replace(/;;.*/g, ""))) throw new Error("unresolved relative reference");
writeFileSync("my-smart-wallet/src/lib/generated.ts",
  `// Generated by scripts/build-wallet-source.mjs. Do not edit.\n` +
  `export const DEPLOYER = ${JSON.stringify(deployer)};\n` +
  `export const SBTC = ${JSON.stringify(sbtc)};\n` +
  `export const WALLET_SOURCE = ${JSON.stringify(code)};\n`);
